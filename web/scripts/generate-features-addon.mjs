#!/usr/bin/env node
/**
 * Emit web/features.js, mesh-bvh-addon.js, and bvh-csg-addon.js from build flags.
 *
 *   MESH_BVH=1  → mesh-bvh impl (wasm --features mesh-bvh)
 *   BVH_CSG=1   → bvh-csg impl + mesh-bvh (wasm --features bvh-csg, implies mesh-bvh)
 *
 * Default build (no flags): both addons point at stubs; features.meshBvh/bvhCsg are false.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const webDir = path.resolve(__dirname, '..');
const pkgJs = path.join(webDir, 'pkg', 'threers.js');

const bvhCsgEnv = process.env.BVH_CSG === '1';
const meshBvhEnv = process.env.MESH_BVH === '1' || bvhCsgEnv;
const pkgHasBvh = fs.existsSync(pkgJs) && fs.readFileSync(pkgJs, 'utf8').includes('WebMeshBvh');
const meshBvh = meshBvhEnv || pkgHasBvh;
const bvhCsg = bvhCsgEnv;

const featuresSrc = `// AUTO-GENERATED by web/scripts/generate-features-addon.mjs — do not edit
/** Build-time feature flags (mirror Cargo [features] in wasm pkg). */
export const features = {
    meshBvh: ${meshBvh},
    bvhCsg: ${bvhCsg},
};

export function isMeshBvhEnabled() {
    return features.meshBvh;
}

export function isBvhCsgEnabled() {
    return features.bvhCsg;
}
`;

const meshBvhAddonSrc = `// AUTO-GENERATED by web/scripts/generate-features-addon.mjs — do not edit
export { features, isMeshBvhEnabled, isBvhCsgEnabled } from './features.js';
export * from './mesh-bvh-${meshBvh ? 'impl' : 'stub'}.js';
`;

const bvhCsgAddonSrc = `// AUTO-GENERATED by web/scripts/generate-features-addon.mjs — do not edit
export { features, isMeshBvhEnabled, isBvhCsgEnabled } from './features.js';
export * from './bvh-csg-${bvhCsg ? 'impl' : 'stub'}.js';
`;

fs.writeFileSync(path.join(webDir, 'features.js'), featuresSrc);
fs.writeFileSync(path.join(webDir, 'mesh-bvh-addon.js'), meshBvhAddonSrc);
fs.writeFileSync(path.join(webDir, 'bvh-csg-addon.js'), bvhCsgAddonSrc);

console.log(`==> features: meshBvh=${meshBvh ? 'on' : 'off'}, bvhCsg=${bvhCsg ? 'on' : 'off'}`);
console.log(`    mesh-bvh addon → ${meshBvh ? 'impl' : 'stub'}`);
console.log(`    bvh-csg addon  → ${bvhCsg ? 'impl' : 'stub'}`);
